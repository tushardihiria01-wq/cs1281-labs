# IT8: The Inspector, Typed

# Asking for a diameter and instantly converting the string to a float for math
diameter = float(input("Enter part diameter for inspection (mm): "))

if 24.95 <= diameter <= 25.05:
    print("ACCEPT: Part is within specification (25.00 ± 0.05).")
else:
    # Nested decision to find out which limit was violated
    if diameter > 25.05:
        print(f"REJECT: Part is too big ({diameter}mm > 25.05mm).")
    elif diameter < 24.95:
        print(f"REJECT: Part is too small ({diameter}mm < 24.95mm).")

# IT6: The Shift Report
import random

# --- EXACT PYTHON LINES FOR COUNTERS (Initialization) ---
accepted_count = 0
rejected_count = 0

print("Starting automated batch inspection...")

# --- EXACT PYTHON LINE FOR THE LOOP ---
for i in range(10):
    # Simulating a part coming down the line with a random diameter between 24.90 and 25.10
    part_diameter = round(random.uniform(24.90, 25.10), 3)

    # --- EXACT PYTHON LINE FOR THE DECISION ---
    if 24.95 <= part_diameter <= 25.05:
        # --- EXACT PYTHON LINE FOR COUNTER (Update Accept) ---
        accepted_count += 1
        print(f"Part {i+1}: {part_diameter}mm -> ACCEPT")
    else:
        # --- EXACT PYTHON LINE FOR COUNTER (Update Reject) ---
        rejected_count += 1
        print(f"Part {i+1}: {part_diameter}mm -> REJECT")

# Final Shift Report
print("--- SHIFT REPORT ---")
print(f"10 inspected · {accepted_count} accepted · {rejected_count} rejected")

