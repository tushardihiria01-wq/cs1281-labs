# IT10: The Full Pipeline
import csv
from pathlib import Path

DATA_DIR = Path("data")
INPUT_FILE = DATA_DIR / "shift_log.txt"
REPORT_FILE = DATA_DIR / "report.txt"
REJECTS_FILE = DATA_DIR / "rejects.csv"

processed_count = 0
rejects = []
valid_records = []

with open(INPUT_FILE, "r") as f:
    for line_num, line in enumerate(f, 1):
        raw_line = line.strip()
        if not raw_line:
            continue

        processed_count += 1
        parts = raw_line.split(",")

        # Validation
        if len(parts) != 3:
            rejects.append([raw_line, "Malformed line structure"])
            continue

        part_id, thickness_str, status = [p.strip() for p in parts]

        try:
            thickness = float(thickness_str)
            valid_records.append((part_id, thickness, status))
        except ValueError:
            rejects.append([raw_line, f"Invalid thickness value: '{thickness_str}'"])

# Aggregate & Write Human Report
with open(REPORT_FILE, "w") as rf:
    rf.write(f"{'PART ID':<10} | {'THICKNESS (mm)':<15} | {'STATUS':<10}\n")
    rf.write("-" * 42 + "\n")
    for pid, thick, stat in valid_records:
        rf.write(f"{pid:<10} | {thick:<15.2f} | {stat:<10}\n")

    rf.write("-" * 42 + "\n")
    rf.write(f"Total Processed: {processed_count}\n")
    rf.write(f"Total Rejects: {len(rejects)}\n")

# Write Rejects CSV
with open(REJECTS_FILE, "w", newline="") as cf:
    writer = csv.writer(cf)
    writer.writerow(["Raw_Line", "Reject_Reason"])
    writer.writerows(rejects)

print(f"Pipeline complete. Check {REPORT_FILE.name} and {REJECTS_FILE.name}.")

# IT8: Regex on Real Text
import re
from pathlib import Path

DATA_DIR = Path("data")
INPUT_FILE = DATA_DIR / "shift_log.txt"

# Regex pattern:
# ^\s*        -> optional leading space
# (P\d{3})    -> Group 1: 'P' followed by exactly 3 digits
# \s*,\s*     -> comma with optional spaces around it
# ([\d\.]+)   -> Group 2: numeric value (thickness)
# \s*,\s*     -> comma with optional spaces
# (ACCEPT|REJECT) -> Group 3: exact status
# \s*$        -> optional trailing space
pattern = re.compile(r"^\s*(P\d{3})\s*,\s*([\d\.]+)\s*,\s*(ACCEPT|REJECT)\s*$")

# OLD VERSION (String split):
# parts = raw_line.split(",")
# if len(parts) == 3: ...
# NOTE: The Regex version survives more test lines because it inherently validates
# the part ID shape (P001 vs P-ABC) and strips whitespace simultaneously, rejecting
# bad formats before they even hit the float() conversion.

valid_records = []
regex_rejects = []

with open(INPUT_FILE, "r") as f:
    for raw_line in f:
        raw_line = raw_line.strip()
        if not raw_line:
            continue

        match = pattern.match(raw_line)
        if match:
            part_id = match.group(1)
            thickness = float(match.group(2))
            status = match.group(3)
            valid_records.append((part_id, thickness, status))
        else:
            regex_rejects.append(raw_line)

print(f"Regex parsed {len(valid_records)} valid records and caught {len(regex_rejects)} filthy lines.")

# IT6: The Batch Job
import re
import csv
from datetime import datetime
from pathlib import Path

DATA_DIR = Path("data")
HISTORY_FILE = DATA_DIR / "run_history.csv"
pattern = re.compile(r"^\s*(P\d{3})\s*,\s*([\d\.]+)\s*,\s*(ACCEPT|REJECT)\s*$")

def process_file(filepath):
    """Parses a single file and returns stats."""
    processed = 0
    rejects = 0
    valid_records = []

    with open(filepath, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue

            processed += 1
            match = pattern.match(line)
            if match:
                valid_records.append((match.group(1), float(match.group(2)), match.group(3)))
            else:
                rejects += 1

    # Write individual file report
    report_path = filepath.with_suffix('.report.txt')
    with open(report_path, "w") as rf:
        rf.write(f"--- BATCH REPORT: {filepath.name} ---\n")
        rf.write(f"Processed: {processed} | Rejects: {rejects}\n")

    return processed, rejects

def main():
    plant_processed = 0
    plant_rejects = 0
    files_processed = 0

    # Ensure history file has headers if it doesn't exist
    if not HISTORY_FILE.exists():
        with open(HISTORY_FILE, "w", newline="") as hf:
            csv.writer(hf).writerow(["Timestamp", "Filename", "Records_Processed", "Rejects"])

    # Loop over every .txt file in the directory (excluding reports)
    for txt_file in DATA_DIR.glob("*.txt"):
        if ".report." in txt_file.name:
            continue

        processed, rejects = process_file(txt_file)

        plant_processed += processed
        plant_rejects += rejects
        files_processed += 1

        # Append to run history
        with open(HISTORY_FILE, "a", newline="") as hf:
            writer = csv.writer(hf)
            writer.writerow([
                datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                txt_file.name,
                processed,
                rejects
            ])

    print("--- PLANT SUMMARY ---")
    print(f"Files Processed: {files_processed}")
    print(f"Total Records: {plant_processed}")
    print(f"Total Rejects: {plant_rejects}")
    print(f"Run history appended to {HISTORY_FILE.name}")

if __name__ == "__main__":
    main()

