day_lines = [
    "P101   25.50   Day",
    "P103    28.75   Day",
    "P105   26.40   Day",
    "P107    31.25   Day",
    "P109   33.50   Day"
]
night_lines = [
    "P102  30.20   Night",
    "P104  32.10   Night",
    "P106  29.90   Night",
    "P108  27.80   Night",
    "P109  33.50   Night"
]
def process_shift(lines):
    accepted = []
    rework = []
    scrap = []

    for line in lines:
        fields = line.split()

        part_code = fields[0]
        diameter = float(fields[1])
        shift = fields[2]

        if 25.0 <= diameter <= 30.0:
            accepted.append(part_code)

        elif 30.0 < diameter <= 32.0:
            rework.append(part_code)

        else:
            scrap.append(part_code)

    return accepted, rework, scrap
day_accepted, day_rework, day_scrap = process_shift(day_lines)
night_accepted, night_rework, night_scrap = process_shift(night_lines)
day_total = len(day_lines)
night_total = len(night_lines)
day_accept_rate = (len(day_accepted) / day_total) * 100
night_accept_rate = (len(night_accepted) / night_total) * 100
day_scrap_set = set(day_scrap)
night_scrap_set = set(night_scrap)
common_scrap = day_scrap_set & night_scrap_set
day_only_scrap = day_scrap_set - night_scrap_set
night_only_scrap = night_scrap_set - day_scrap_set
print("DAY SHIFT")
