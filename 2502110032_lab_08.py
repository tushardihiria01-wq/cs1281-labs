# IT10: Robust Parser with Rejects and Guarded Average
def parse_line(line):
    """
    Parses a comma-separated line. Expected format: JobID, Value1, Value2
    """
    if not line.strip():
        raise ValueError("Empty or whitespace-only line")

    parts = [p.strip() for p in line.split(',')]
    if len(parts) < 3:
        raise ValueError(f"Insufficient fields: expected at least 3, got {len(parts)}")

    job_id = parts[0]
    try:
        val1 = float(parts[1])
        val2 = float(parts[2])
    except ValueError as ve:
        raise ValueError(f"Non-numeric values in fields: {ve}")

    return job_id, val1, val2

def run_parser(lines):
    report = []
    rejects = []

    for line_num, line in enumerate(lines, 1):
        try:
            job_id, v1, v2 = parse_line(line)

            # Guarded average to prevent division by zero or numerical issues
            if v2 == 0:
                raise ZeroDivisionError("Second numeric value is zero, average calculation guarded.")

            average = (v1 + v2) / 2.0
            report.append({"job_id": job_id, "v1": v1, "v2": v2, "average": average})

        except (ValueError, ZeroDivisionError) as e:
            rejects.append({"line_num": line_num, "raw_line": line, "reason": str(e)})

    return report, rejects

