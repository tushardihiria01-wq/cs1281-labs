import random
import csv
import time
from datetime import datetime
from pathlib import Path

class StampingPress:
    """Simulates an industrial stamping press with integrated Quality Control."""

    def __init__(self, machine_id, target_thickness=10.0, tolerance=0.5):
        self.machine_id = machine_id
        self.target = target_thickness
        self.upper_limit = target_thickness + tolerance
        self.lower_limit = target_thickness - tolerance
        self.history = []

    def run_batch(self, batch_size):
        print(f"\n--- STARTING MACHINE {self.machine_id} ---")
        print(f"Target: {self.target}mm | Limits: [{self.lower_limit}mm to {self.upper_limit}mm]")
        print("-" * 50)

        accepted = 0
        rejected = 0

        for i in range(1, batch_size + 1):
            # Simulate slight machine wear and random variation
            actual_thickness = round(random.uniform(9.2, 10.8), 2)
            part_id = f"PRT-{i:03d}"

            # Inspection Logic
            if self.lower_limit <= actual_thickness <= self.upper_limit:
                status = "ACCEPT"
                accepted += 1
            else:
                status = "REJECT"
                rejected += 1

            # Log the data
            record = {
                "Timestamp": datetime.now().strftime("%H:%M:%S"),
                "Part_ID": part_id,
                "Thickness_mm": actual_thickness,
                "Status": status
            }
            self.history.append(record)

            # Live console feed
            print(f"[{record['Timestamp']}] {part_id} | {actual_thickness}mm | {status}")
            time.sleep(0.1) # Brief pause for simulated mechanical cycle

        return accepted, rejected

    def export_csv(self, filename="shift_production_log.csv"):
        """Exports the machine's run history to a CSV file."""
        if not self.history:
            print("No data to export.")
            return

        filepath = Path.cwd() / filename
        with open(filepath, mode="w", newline="") as file:
            writer = csv.DictWriter(file, fieldnames=["Timestamp", "Part_ID", "Thickness_mm", "Status"])
            writer.writeheader()
            writer.writerows(self.history)

