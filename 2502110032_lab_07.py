class Machine:
    def __init__(self, name: str, speed_rating: float):
        # At least three attributes (name, speed_rating, and job count tracker)
        self.name = name
        self.speed_rating = speed_rating
        self.jobs_processed = 0

    def __str__(self) -> str:
        return f"[Machine: {self.name} | Max Speed: {self.speed_rating} | Processed: {self.jobs_processed}]"

    def process_job(self, complexity: float):
        """Working method to process a job based on machine capability."""
        if complexity <= self.speed_rating:
            self.jobs_processed += 1
            print(f"-> {self.name} successfully processed job with complexity {complexity}.")
        else:
            print(f"-> {self.name} cannot process job: complexity {complexity} exceeds capacity {self.speed_rating}.")

